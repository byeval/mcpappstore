export const appEditorial: Record<string, AppEditorial> = Object.fromEntries(
  entries.map(
    ([id, sourceUrl, useCase, check, prompt, zhUseCase, zhCheck, zhPrompt]) => [
      id,
      {
        sourceUrl,
        reviewedAt: "2026-11-11",
        scope: "documentation",
        en: { useCase, check, prompt },
        zh: { useCase: zhUseCase, check: zhCheck, prompt: zhPrompt },
      },
    ],
  ),
);
export function editorialFor(id: string, locale: Locale) {
  const record = appEditorial[id];
  return record
    ? {
        ...record,
        ...(locale === "zh-hans" ? record.zh : record.en),
        lang: locale === "zh-hans" ? "zh-Hans" : "en",
      }
    : undefined;
}
