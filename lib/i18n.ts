const localeSet = new Set<string>(supportedLocales);

export function isLocale(value: string | undefined | null): value is Locale {
  return Boolean(value && localeSet.has(value));
}

export function normalizeLocale(value: string | undefined | null): Locale | undefined {
  if (!value) {
    return undefined;
  }

  const normalized = value.toLowerCase().trim().replace("_", "-");
  if (isLocale(normalized)) {
    return normalized;
  }

  const [base] = normalized.split("-");
  if (isLocale(base)) {
    return base;
  }

  if (normalized === "zh" || normalized === "zh-cn" || normalized === "zh-sg" || normalized.startsWith("zh-hans")) {
    return "zh-hans";
  }

  if (normalized === "jp" || normalized === "ja-jp") {
    return "ja";
  }

  if (normalized === "kr" || normalized === "ko-kr") {
    return "ko";
  }

  return undefined;
}

export function localeFromPath(pathname: string): Locale | undefined {
  const [segment] = pathname.replace(/^\/+/, "").split("/");
  return normalizeLocale(segment);
}

export function stripLocaleFromPath(pathname: string): string {
  const cleanPath = pathname.startsWith("/") ? pathname : `/${pathname}`;
  const pathWithoutLeadingSlash = cleanPath.replace(/^\/+/, "");
  const slashIndex = pathWithoutLeadingSlash.indexOf("/");
  const segment = slashIndex === -1 ? pathWithoutLeadingSlash : pathWithoutLeadingSlash.slice(0, slashIndex);
  if (!normalizeLocale(segment)) {
    return cleanPath || "/";
  }

  return slashIndex === -1 ? "/" : `/${pathWithoutLeadingSlash.slice(slashIndex + 1)}`;
}

export function localizedPath(path: string, locale: Locale, options: { includeDefaultLocale?: boolean } = {}): string {
  const [pathWithQuery, hash = ""] = path.split("#", 2);
  const [pathname = "/", query = ""] = pathWithQuery.split("?", 2);
  const cleanPath = stripLocaleFromPath(pathname || "/");
  const shouldPrefixDefaultLocale = options.includeDefaultLocale && locale === defaultLocale;
  const localized = locale === defaultLocale && !shouldPrefixDefaultLocale
    ? cleanPath
    : cleanPath === "/"
      ? `/${locale}`
      : `/${locale}${cleanPath}`;
  const withQuery = query ? `${localized}?${query}` : localized;

  return hash ? `${withQuery}#${hash}` : withQuery;
}

export function detectLocaleFromAcceptLanguage(header: string | undefined | null): Locale {
  if (!header) {
    return defaultLocale;
  }

  const candidates = header
    .split(",")
    .map((part) => {
      const [tag = "", quality = "q=1"] = part.trim().split(";");
      const q = quality.startsWith("q=") ? Number.parseFloat(quality.slice(2)) : 1;
      return {
        locale: normalizeLocale(tag),
        q: Number.isFinite(q) ? q : 0,
      };
    })
    .filter((candidate): candidate is { locale: Locale; q: number } => Boolean(candidate.locale))
    .sort((left, right) => right.q - left.q);

  return candidates[0]?.locale ?? defaultLocale;
}

export function formatMessage(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
}

